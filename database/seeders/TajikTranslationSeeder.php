/**
 * Tajik texts for the demo content.
 *
 * Fills the "tj" value of translatable fields whose Russian text is known below,
 * when it is empty or still a copy of the Russian one; translations made in the
 * admin are never overwritten, so the seeder is safe to run again.
 */
class TajikTranslationSeeder extends Seeder
{
    /** @var list<class-string<Model>> */
    protected array $models = [
        Course::class, Employee::class, Certificate::class, Gallery::class, News::class,
        Review::class, Advantage::class, Faq::class, Service::class,
    ];

    public function run(): void
    {
        foreach ($this->models as $model) {
            foreach ($model::all() as $record) {
                foreach ($record->translatableAttributes() as $attribute) {
                    $record->{$attribute} = $this->translate($record->getTranslations($attribute));
                }

                if ($record instanceof Course && $record->blocks) {
                    $record->blocks = array_map(fn (array $block) => [
                        ...$block,
                        'title' => $this->translate($block['title'] ?? []),
                        'items' => $this->translate($block['items'] ?? []),
                    ], $record->blocks);
                }

                $record->save();
            }
        }
    }

    /**
     * @param  array<string, string|null>  $values
     * @return array<string, string|null>
     */
    protected function translate(array $values): array
    {
        $ru = $values['ru'] ?? null;
        $tj = $values['tj'] ?? null;

        if (filled($ru) && isset(static::TEXTS[$ru]) && (blank($tj) || $tj === $ru)) {
            $values['tj'] = static::TEXTS[$ru];
        }

        return $values;
    }

